  function isVowel(ch) { return VOWELS.indexOf(ch) >= 0; }

  function regions(word) {
    let rv = word.length, r1 = word.length, r2 = word.length;
    for (let i = 0; i < word.length; i++) {
      if (isVowel(word[i])) { rv = i + 1; break; }
    }
    for (let i = 1; i < word.length; i++) {
      if (!isVowel(word[i]) && isVowel(word[i - 1])) { r1 = i + 1; break; }
    }
    for (let i = r1 + 1; i < word.length; i++) {
      if (!isVowel(word[i]) && isVowel(word[i - 1])) { r2 = i + 1; break; }
    }
    return { rv, r1, r2 };
  }

