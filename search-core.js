  const ALPHA = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_';
  const ALPHA_IDX = {};
  for (let i = 0; i < ALPHA.length; i++) ALPHA_IDX[ALPHA[i]] = i;

  function encodeList(nums) {
    let s = '', prev = -1;
    for (const n of nums) {
      let d = n - prev - 1;
      prev = n;
      while (d >= 32) { s += ALPHA[32 + (d & 31)]; d = Math.floor(d / 32); }
      s += ALPHA[d];
    }
    return s;
  }

  function decodeList(s) {
    const out = [];
    let prev = -1, val = 0, shift = 1;
    for (let i = 0; i < s.length; i++) {
      const c = ALPHA_IDX[s[i]];
      if (c >= 32) { val += (c - 32) * shift; shift *= 32; }
      else { val += c * shift; prev = prev + val + 1; out.push(prev); val = 0; shift = 1; }
    }
    return out;
  }

