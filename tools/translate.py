# ------------------------------------------------------------------ вирівнювання форм RU↔UA
# Багато пасток — не в слові, а у ВІДМІНКУ: Google лишає «приливы жара» як «припливи спека»
# (називний замість родового). Відмінок видно в оригіналі, тож k-те слово українського тексту
# правимо за k-ю формою російського; якщо кількості не збіглись — не чіпаємо нічого.
# «ом»/«ем» сюди не можна: це і закінчення іменників («с изъязвлением, поражением…»),
# а «-ние/-тие» на -ие збігається з множиною прикметника («Ощущение жара» — іменник, не прикметник)
RU_ADJ_END = re.compile(r"(ый|ий|ая|яя|ое|ее|ого|его|ому|ему|ым|им|ыми|ими|ую|юю|ые|ие|ых|их)$", re.I)
RU_NOUN_END = re.compile(r"(ние|тие|вие|бие|ция|сия)$", re.I)
RU_ADJ_STOP = {"его", "ее", "их", "им", "ими", "этом", "этим", "том", "тем", "всем", "самом", "самим", "нем", "ним", "чем",
               "который", "которая", "которое", "которые", "которым", "которых", "многие", "некоторые", "такие", "эти", "те"}
# короткі присудкові форми: «характерно поражение…» — прикметник, хоч і на -о
RU_ADJ_SHORT = {"характерно", "типично", "выражено", "свойственно", "обусловлено", "показано"}


def _align_fix(ru: str, ua: str, ru_re, ua_re, fix):
    """fix(ru_форма, m_ru, m_ua) → список замін [(start, end, text)] в ua; порожній — лишити як є."""
    ru_ms = list(ru_re.finditer(ru))
    ua_ms = list(ua_re.finditer(ua))
    if not ru_ms or len(ru_ms) != len(ua_ms):
        return ua
    spans = []
    for m_ru, m_ua in zip(ru_ms, ua_ms):
        spans += fix(m_ru.group(0).lower(), m_ru, m_ua) or []
    if not spans:
        return ua
    out, pos = [], 0
    for a, b, t in sorted(spans):
        if a < pos:
            continue
        out.append(ua[pos:a])
        out.append(t)
        pos = b
    out.append(ua[pos:])
    return "".join(out)


def _agree_before(ru: str, ru_pos: int, ua: str, ua_pos: int, table, nmax=2):
    """Узгоджує до nmax слів перед ua_pos — але лише ті, для яких слово на тому ж місці
    в російському реченні є прикметником (там рід/відмінок ще правильні)."""
    ru_words = re.findall(r"[А-Яа-яЁё’'\-]+", ru[:ru_pos])
    ua_words = list(re.finditer(r"[А-ЯІЇЄҐа-яіїєґ’'\-]+", ua[:ua_pos]))
    ends = sorted(table, key=len, reverse=True)
    spans = []
    for k in range(1, nmax + 1):
        if len(ru_words) < k or len(ua_words) < k:
            break
        rw = ru_words[-k].lower()
        if rw in RU_ADJ_STOP or RU_NOUN_END.search(rw) or not (RU_ADJ_END.search(rw) or rw in RU_ADJ_SHORT):
            break
        m = ua_words[-k]
        w, low, rep = m.group(0), m.group(0).lower(), None
        for src in ends:
            if low.endswith(src) and len(low) > len(src) + 2:
                rep = w[: len(w) - len(src)] + table[src]
                break
        if rep is None:
            break
        spans.append((m.start(), m.end(), rep))
    return spans


def fix_terms(ru: str, ua: str, ru_orig: str = None) -> str:
    s = ua
    # лізик (стенд-ін) → язик
    s = re.sub(LB + r"([Лл])[иі]зи(к|ц)", lambda m: ("Я" if m.group(1) == "Л" else "я") + "зи" + m.group(2), s)
    s = re.sub(r"(?<=[Нн]а )[Лл][иі]зи" + RB + "|(?<=[УуВв] )[Лл][иі]зи" + RB, "язиці", s)
    # «Лизи чисті, червоні» / «Лізино набряклий» (варіанти Google для стенд-іна) → «Язик чистий, червоний»
    def lizy(m):
        words = m.group(2).split(" ")
        out = []
        stop = False
        for w in words:
            lw = w.rstrip(",;")
            tail = w[len(lw):]
            if not stop and re.match(r"[а-яіїєґ’']+[аяі]$", lw) and lw not in ("і", "та", "й", "дуже", "трохи", "інколи", "іноді", "зазвичай", "спочатку", "потім", "місцями", "особливо"):
                lw = lw[:-1] + ("ій" if lw.endswith("я") else "ий")
            elif lw in ("і", "та", "й") or not re.match(r"[а-яіїєґ’']+[аяі]$", lw):
                stop = True
            out.append(lw + tail)
        return m.group(1) + "Язик " + " ".join(out)
    s = re.sub(r"(^|[.;!?]\s+|\*\*|_)[Лл][иі]зи(?:но)? ((?:[а-яіїєґ’']+[,;]?\s?){1,4})", lizy, s)
    s = re.sub(LB + r"([Лл])[иі]зи(?:но|)" + RB, lambda m: ("Я" if m.group(1) == "Л" else "я") + "зик", s)
    # «Язика волога, обкладена» (Google дав родовий + жіночий рід) → «Язик вологий, обкладений»
    def sent_init(m):
        words = m.group(2).split(" ")
        out = []
        for w in words:
            lw = w.rstrip(",;")
            tail = w[len(lw):]
            if re.match(r"[а-яіїєґ’']+[ая]$", lw) and lw not in ("дуже", "трохи", "інколи", "іноді", "зазвичай", "спочатку", "потім", "місцями"):
                lw = lw[:-1] + ("ий" if lw.endswith("а") else "ій")
            out.append(lw + tail)
        return m.group(1) + "Язик " + " ".join(out)
    s = re.sub(r"(^|[.;!?]\s+|\*\*|_)Язика ((?:[а-яіїєґ’']+[,;]?\s?){1,4})", sent_init, s)
    # рожа → бешиха
    if re.search(LB + r"рож[аиеуоы]" + RB + "|" + LB + "рожей" + RB, ru, re.I) and re.search(LB + r"пи[кц]", s, re.I) and not re.search(r"мерещ|видит|снятся|чудится|страшные рожи|корчит", ru, re.I):
        forms = {"пика": "бешиха", "пики": "бешихи", "пиці": "бешисі", "пику": "бешиху", "пикою": "бешихою", "пик": "беших"}
        s = re.sub(LB + r"([Пп]ика|[Пп]ики|[Пп]иці|[Пп]ику|[Пп]икою|[Пп]ик)" + RB, lambda m: _case(m.group(1), forms[m.group(1).lower()]), s)
    # виски → скроні (крім віскі-напою)
    if re.search(r"\bвиск(и|ах|ов|е|ом|ами)\b", ru, re.I) and not re.search(r"желани|пить|напит|алкогол|бренди|водк|\bпив[ао]\b|\bвин[оа]\b|коньяк|ликер|спиртн", ru, re.I):
        s = re.sub(LB + r"([Вв])іскі" + RB, lambda m: _case(m.group(1), "скроні"), s)
    # течія → перебіг (з узгодженням прикметника перед і після)
    if re.search(r"\bтечени[еяюи]\b|\bтечением\b", ru, re.I) and re.search(r"\bтечі", s, re.I):
        def conv_adj(w, case_end):
            low = w.lower()
            for src, dst in TECH_FEM2MASC.items():
                if low.endswith(src) and (case_end is None or src in case_end):
                    return w[: len(w) - len(src)] + dst
            return w
        forms = {"течія": "перебіг", "течії": "перебігу", "течію": "перебіг", "течією": "перебігом"}
        ends = {"течія": ("а", "я"), "течії": ("ої", "ьої", "ій"), "течію": ("у", "ю"), "течією": ("ою", "ьою")}
        STOP = {"хоча", "сама", "сам", "ця", "та", "вся", "яка", "як", "і", "й", "а", "не", "же", "вже", "лише", "має", "була", "буде", "для", "від", "при", "після"}
        def rep(m):
            adjs = (m.group(1) or "").split()
            form = m.group(2).lower()
            out = []
            for a in adjs:
                if a.lower() == "сама":
                    out.append(_case(a, "сам"))
                elif a.lower() in STOP:
                    out.append(a)
