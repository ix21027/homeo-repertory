# Виправлення заперечень, які Google губить (див. tools/check_negation.mjs і README).
# Кожен запис: {ru: <RU-речення>, bad: <UA-речення як його дав перекладач>, good: <правильне UA>}.
# Правило спрацьовує, коли RU-речення є в сегменті, а зіпсоване UA-речення — у результаті.
NEG_FIXES_FILE = os.path.join(ROOT, "tools", "negation-fixes.json")
NEG_FIXES = json.load(open(NEG_FIXES_FILE, encoding="utf-8")) if os.path.exists(NEG_FIXES_FILE) else []
# tools/term-fixes.json — поштучні правки з вичитки корпусу агентами (той самий механізм: фрагмент → фрагмент).
TERM_FIXES_FILE = os.path.join(ROOT, "tools", "term-fixes.json")
if os.path.exists(TERM_FIXES_FILE):
    NEG_FIXES = NEG_FIXES + json.load(open(TERM_FIXES_FILE, encoding="utf-8"))
USED = {}  # id(правки) → чи знайшовся її російський рядок у корпусі


def _loose(s: str):
    """Той самий текст, але стійкий до розділових знаків і пробілів між словами."""
    return re.compile(r"[\s\W_]*".join(re.escape(w) for w in re.findall(r"[^\W_]+", s)))


def _word_span(s: str):
    w = list(re.finditer(r"[^\W_]+", s))
    return (w[0].start(), w[-1].end()) if w else (0, len(s))


def apply_negation_fixes(seg: str, out: str) -> str:
    for fx in NEG_FIXES:
        if fx["ru"] not in seg:
            USED.setdefault(id(fx), False)
            continue
        USED[id(fx)] = True
        if fx["good"] in out:
            continue                                   # вже правильно (те саме речення в іншому місці)
        if fx["bad"] in out:
            out = out.replace(fx["bad"], fx["good"])
            continue
        m = _loose(fx["bad"]).search(out)               # інші пост-правила могли трохи змінити текст
        if m:
            a, b = _word_span(fx["good"])
            out = out[:m.start()] + fx["good"][a:b] + out[m.end():]
            continue
        print(f"fix not applied: {fx.get('note', '')} {fx['ru'][:70]}", file=sys.stderr)
    return out


# --------------------------------------------------------- обірвані переліки латинських назв
# Перелік препаратів у вступі статті («…призначають такі препарати: **Aconitum Aesculus …**»)
# Google ріже: у RU 20-30 назв, в UA лишаються 2-3. Позначок «**…**» довкола ЦІЛОГО сегмента тут
# немає (попереду перекладний вступ), тож правило вище не спрацьовує. Латиною вважаємо слово,
# у якому щонайменше 3 латинські літери і їх більше, ніж кириличних: у джерелі є «Кali», «асidum»,
# «Асоnitum» — назви з кириличними гомогліфами.
WORD_ANY = re.compile(r"[A-Za-zА-Яа-яЁёЇїІіЄєҐґ]+")
# кириличні двійники латинських літер: у джерелі трапляються «Кali», «асidum», «Асоnitum».
# Хвіст RU-переліку копіюється в UA як є, тож двійники нормалізуємо саме тут (решту корпусу
# чистить окремий скрипт) — інакше «Кali» лишається кириличним і Google його транслітерує.
HOMOGLYPH = str.maketrans("АВСЕНІКМОРТХасеіорху", "ABCEHIKMOPTXaceiopxy")


def _delat(tok: str) -> str:
    """Нормалізує кириличні двійники в токені, який уже визнано латинським."""
    return tok.translate(HOMOGLYPH)


def _latish(text):
    out = []
    for m in WORD_ANY.finditer(text):
        lat = len(re.findall(r"[A-Za-z]", m.group(0)))
        if lat >= 3 and lat * 2 > len(m.group(0)):
            out.append(m)
    return out


def fix_latin_list(ru: str, ua: str) -> str:
    ru_t = _latish(ru)
    if len(ru_t) < 4 or len(_latish(ua)) >= len(ru_t):
        return ua
    tail = ru[ru_t[0].start():]
    for m in WORD_ANY.finditer(tail):                 # хвіст має бути чистим переліком
        if not re.search(r"[A-Za-z]", m.group(0)) and m.group(0).lower() != "и":
            return ua
    pre = ru[: ru_t[0].start()]
    bold = pre.rstrip().endswith("**")
    if bold:                                          # «**» відкриває перелік — забираємо в хвіст
        tail = "**" + tail
        pre = pre.rstrip()[:-2]
    sep = re.search(r"([:\-–—])[\s*_]*$", pre)        # роздільник, за яким починається перелік
    cut = None
    if sep:
        cls = "[-–—]" if sep.group(1) in "-–—" else ":"
        n = len(re.findall(cls, pre))
        ms = list(re.finditer(cls, ua))
        if len(ms) >= n:
            cut = ms[n - 1].end()
    if cut is None:
        ua_t = _latish(ua)
        if not ua_t:
            return ua
        cut = ua_t[0].start()
    head = ua[:cut].rstrip()
    if bold:                                          # «**» уже в хвості — в голові його бути не має
        head = head.rstrip("*_ ")
    tail = re.sub(r"\s+и\s+", " і ", tail)
    tail = "".join(_delat(m.group(0)) if _latish(m.group(0)) else m.group(0)
                   for m in re.finditer(r"[A-Za-zА-Яа-яЁёЇїІіЄєҐґ]+|[^A-Za-zА-Яа-яЁёЇїІіЄєҐґ]+", tail))
    return (head + " " if head else "") + tail


def tr(seg):
    if seg in SEG_FIX:
        return SEG_FIX[seg]
    # жирні списки латинських назв (переліки препаратів у статтях) Google обрізає — лишаємо як є
    if re.match(r"^\*\*[^*]{20,}\*\*$", seg.strip()):
        lat = len(re.findall(r"[A-Za-z]", seg)); cyr = len(re.findall(r"[а-яёА-ЯЁ]", seg))
        if lat >= 4 * max(cyr, 1):
            return re.sub(r"\s+и\s+", " і ", seg)
    key = protect_ru(seg)
    if key not in cache:
        return seg
    out = fix_terms(key, cache[key], seg)
    if seg[:1].isupper() and out[:1].islower():
        out = out[0].upper() + out[1:]
    out = fix_latin_list(seg, out)
    # кирилиця всередині латинських назв: у джерелі є «Bгyonia», «Cиprum», «Нераr» — карта
    # двійників їх не бере (у «г», «и» латинських двійників немає), тож звіряємо з каталогом назв
    out = fix_homoglyphs.fix_latin_names(out)
    out = apply_negation_fixes(seg, out)
    # склеєні речення: Google загубив пробіл після крапки перед номером пункту або лапками.
    # Після поштучних правок — вони самі приносять такі склейки («…збудження."Ніколи» → «…«Ніколи»).
    return re.sub(r"(?<=[а-яіїєґ]{2})\.(?=\d\)|«)", ". ", out)


def render_ua(fm, body, kind):
    out_fm = []
    latin = alt = ""
    for k, v in fm:
        if k == "latin":
            latin = v
        if k == "alt_latin":
            alt = v
    for k, v in fm:
        if k == "sections":
            v = "; ".join(SECTION_UA.get(x.strip(), x.strip()) for x in v.split(";"))
        elif k == "transliteration":
            v = " = ".join(tr(p.strip()) for p in v.split(" = "))
        elif k in ("common", "source", "author"):
            v = tr(v)
        elif k == "title":
            if kind == "article":
                v = tr(v)
            else:
                translit = " = ".join(tr(p.strip()) for p in dict(fm).get("transliteration", "").split(" = ")) if dict(fm).get("transliteration") else ""
                common = tr(dict(fm).get("common", "")) if dict(fm).get("common") else ""
                v = latin + (f" ({alt})" if alt else "") + (f" ({translit})" if translit else "") + (f" — {common}" if common else "")
        elif k in ("lang", "keywords"):
            continue
        out_fm.append((k, v))
    out_fm.insert(1, ("lang", "ua"))
    lines = []
    in_clinic = False
    for line in body.split("\n"):
        if not line.strip():
            lines.append("")
            continue
        h2 = HEADER2_RE.match(line)
        if h2:
            t = h2.group(1).strip()
            in_clinic = t == "Клиника"
            lines.append("## " + SECTION_UA.get(t, tr(t)))
            continue
        h3 = HEADER3_RE.match(line)
        if h3:
            lines.append("### " + "".join(tr(text.strip()) if t else text for text, t in header3_parts(h3.group(1).strip())))
            continue
        if in_clinic:
            terms = [tr(t) for t in split_terms(line)]
            lines.append(". ".join(t.rstrip(".") for t in terms) + ("." if terms else ""))
            continue
        if line.startswith("- "):
            lines.append("- " + tr(line[2:]))
        else:
            lines.append(tr(line))
    fm_text = "---\n" + "\n".join(f"{k}: {v}" for k, v in out_fm if v) + "\n---\n"
    return fm_text + "\n".join(lines).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()
    files = []
    for sub in ("remedies", "articles"):
        os.makedirs(os.path.join(DST, sub), exist_ok=True)
        for fn in sorted(os.listdir(os.path.join(SRC, sub))):
            if not fn.endswith(".md"):
                continue
            dst = os.path.join(DST, sub, fn)
            if os.path.exists(dst) and not args.force:
                continue
            files.append((sub, fn))
    print(f"files to translate: {len(files)}", flush=True)
    parsed = {}
    all_segs = []
    for sub, fn in files:
        text = open(os.path.join(SRC, sub, fn), encoding="utf-8").read()
        fm, body = parse_md(text)
        kind = "article" if sub == "articles" else "remedy"
        parsed[(sub, fn)] = (fm, body, kind)
        all_segs.extend(collect_segments(fm, body, kind))
    translate_all(all_segs, workers=args.workers)
    retry_leftovers()
    missing = 0
    for (sub, fn), (fm, body, kind) in parsed.items():
        segs = collect_segments(fm, body, kind)
        if any(need_translation(s) and protect_ru(s) not in cache for s in segs):
            missing += 1
            continue
        open(os.path.join(DST, sub, fn), "w", encoding="utf-8").write(render_ua(fm, body, kind))
    print(f"written: {len(parsed) - missing}, skipped (untranslated segments remain): {missing}", flush=True)
    orphan = sum(1 for fx in NEG_FIXES if not USED.get(id(fx)))
    if orphan:
        print(f"УВАГА: {orphan} правок не знайшли свого російського рядка (див. tools/negation-fixes.json, tools/term-fixes.json)", file=sys.stderr)


if __name__ == "__main__":
    main()
