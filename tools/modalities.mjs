function applyExcl(cats, table) {
  const set = new Set(cats);
  for (const c of cats) for (const x of (table[c] || [])) set.delete(x);
  return Array.from(set);
}

export function classifyMod(clause) {
  const c = clause.toLowerCase().replace(/ё/g, 'е');
  const cats = [];
  for (const [key, re] of MOD_CATS) if (re.test(c)) cats.push(key);
  return applyExcl(cats, MOD_EXCL);
}
export function classifyEtio(clause) {
  const c = clause.toLowerCase().replace(/ё/g, 'е');
  const cats = [];
  for (const [key, re] of ETIO_CATS) if (re.test(c)) cats.push(key);
  return applyExcl(cats, ETIO_EXCL);
}

// Розбиває абзац модальностей на фрази; повертає [{d:'w'|'b', t:фраза}]
export function splitClauses(text) {
  return text.replace(/\*\*|_/g, '').split(/[.;]\s+|\.$|:\s+(?=[А-ЯA-Z])/).map(s => s.replace(/^[\s•\-–—]+|[\s.;]+$/g, '')).filter(s => s.length >= 2);
}

// Абзаци розділу «Модальности» → [{d, c:[keys], t}] з успадкуванням напрямку
export function parseModalities(paras) {
  const out = [];
  let dir = null;
  let stats = { clauses: 0, assigned: 0, unassigned: [] };
  for (const p of paras) {
    let text = p.replace(/^\s*-\s*/, '');
    const m = text.match(/^\*\*\s*•?\s*(Хуже|Лучше|Гірше|Краще)[.:]?\s*([а-яёА-ЯЁіїєІЇЄ]*)\*\*[.:]?\s*/);
    let pdir = dir;
    if (m) {
      pdir = /Хуже|Гірше/.test(m[1]) ? 'w' : 'b';
      text = (m[2] ? m[2] + ' ' : '') + text.slice(m[0].length);
      dir = pdir;
    } else if (/ослабева|облегча|улучш|уменьша/.test(text) && !/усилив|ухудш/.test(text)) pdir = 'b';
    else if (/усилив|ухудш/.test(text) && !/ослабева|облегча|улучш|уменьша/.test(text)) pdir = 'w';
    if (!pdir) continue;
    for (const cl of splitClauses(text)) {
      if (/^(хуже|лучше)$/i.test(cl)) continue;
      stats.clauses++;
      let d = pdir;
      const head = dropExcept(cl);
      const low = head.toLowerCase().replace(/ё/g, 'е');
      if (!head || NEG_MOD.test(low)) { stats.unassigned.push(cl); continue; }
      if (d === 'w' && FLIP_TO_BETTER.test(low) && !FLIP_TO_WORSE.test(low)) d = 'b';
      else if (d === 'b' && FLIP_TO_WORSE.test(low) && !FLIP_TO_BETTER.test(low)) d = 'w';
      const c = classifyMod(head);
      if (c.length) stats.assigned++; else stats.unassigned.push(cl);
      out.push({ d, c, t: cl });
    }
  }
  return { items: out, stats };
}

export function parseEtiology(paras) {
  const out = [];
  const stats = { clauses: 0, assigned: 0, unassigned: [] };
  for (const p of paras) {
    const text = p.replace(/^\s*-\s*/, '').replace(/^\*\*[^*]{0,40}\*\*[.:]?\s*/, '');
    for (const cl of splitClauses(text)) {
      stats.clauses++;
      const c = classifyEtio(cl);
      if (c.length) stats.assigned++; else stats.unassigned.push(cl);
      out.push({ c, t: cl });
    }
  }
  return { items: out, stats };
}

// Взаимосвязи: [{k, t:підпис, names:[рядки назв]}]
const REL_KINDS = [
  ['ant', /антидот/], ['incompat', /несовместим/], ['compl', /совместим|дополн|комплимент|комплемент|дополнительн/],
  ['after', /следует (за|после)|действует после|показан после|назначать после|после (него|неё|нее|.{3,40}) хорошо/], ['before', /за (ним|ней) (хорошо )?следу|после .{3,40} (хорошо )?(следу|назнач)/],
  ['cmp', /сравн|подобн|сходн|дифференц|напоминает|аналог|родств|близк/],
];
export function parseRelations(paras) {
  const out = [];
  for (const p of paras) {
    const re = /\*\*([^*]{2,90})\*\*[:.]?\s*([^*]+)/g;
    let m;
    while ((m = re.exec(p)) !== null) {
      const label = m[1].replace(/[:.]+$/, '').trim();
      let kind = 'other';
      const low = label.toLowerCase().replace(/ё/g, 'е');
      for (const [k, r] of REL_KINDS) if (r.test(low)) { kind = k; break; }
      if (kind === 'after' && /^после .{3,40} хорошо/.test(low)) kind = 'before';
      if (kind === 'other' && /является антидотом|антидотом (для|при)/.test(low)) kind = 'ant';
      const body = m[2].replace(/\([^)]*\)/g, ' ').replace(/\s+/g, ' ').trim();
      const names = body.split(/[,;]\s*|\s+(?:и|а также|или|затем)\s+|\.\s+/).map(s => s.replace(/^(?:и|а также|или|затем|при|для|—|-)\s+/, '').replace(/[.:]+$/, '').trim()).filter(Boolean);
      out.push({ k: kind, t: label, names });
    }
  }
  return out;
}

