// У JS `\w` і `\b` не знають кирилиці, тому регекси таблиць переписуються: \w → [а-яёa-z],
// \b → (?<![а-яёa-z0-9]) / (?![а-яёa-z0-9]).
function cy(re) {
  let src = re.source.replace(/\\w/g, '[а-яёa-z]');
  src = src.replace(/\\b(?=[а-яё0-9(\[\\])/g, '(?<![а-яёa-z0-9])').replace(/\\b/g, '(?![а-яёa-z0-9])');
  return new RegExp(src, re.flags);
}
const cyTable = t => t.map(([k, re, ru, ua]) => [k, cy(re), ru, ua]);

