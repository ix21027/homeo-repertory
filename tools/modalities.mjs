// Фаза 2: видобування модальностей із симптомних розділів
// ---------------------------------------------------------------------------
// У симптомних розділах модальність записана всередині речення про симптом
// («Боль в горле облегчается от теплого питья», «На свежем воздухе усиливается
// головокружение»). Беремо лише речення з явним маркером напрямку і класифікуємо
// НЕ все речення, а вікно біля маркера: інакше `motion` ловив би «усилие» з самого
// маркера, а `heat` — «жар» із назви симптому.

// [regex маркера, напрямок, сила]. Сильні маркери приймають широкий набір прийменників,
// слабкі — лише причинні («проходит от», «легче при»), бо самі по собі багатозначні
// («боль проходит по ходу нерва»).
const MINE_MARKS = cyTable([
  ['no-tolerate', /не перенос(ит|ят|ил|ила|ило|или)|не выносит|не выносят|непереносимост\w*/, 'w', 'direct'],
  ['worse-strong', /хуже|ухудша\w*|ухудшен\w*|усилива\w*|усиливш\w*|усугубля\w*|обостря\w*|возобновля\w*/, 'w', 'strong'],
  ['worse-weak', /невыносим\w*|тяжелее|мучительнее|болезненнее/, 'w', 'weak'],
  ['better-strong', /лучше|улучша\w*|улучшен\w*|облегча\w*|облегчен\w*|ослабева\w*|ослабля\w*|уменьша\w*|смягча\w*|успокаива\w*/, 'b', 'strong'],
  ['better-weak', /стиха\w*|утиха\w*|проход(ит|ят|ила|ило|или|ящ\w*)|прекраща\w*|исчеза\w*|легче/, 'b', 'weak'],
]);
// Один прохід по реченню: усі маркери разом, щоб знати межі сусіднього маркера.
const MINE_RE = new RegExp(MINE_MARKS.map(([, re]) => '(?:' + re.source + ')').join('|'), 'gi');
const MINE_DIR = MINE_MARKS.map(([, re, d, kind]) => [new RegExp('^(?:' + re.source + ')$', 'i'), d, kind]);

// Перехідні дієслова: підмет перед ними — це причина, а не симптом («Теплое питье
// уменьшает кашель»). «ослабевает» сюди не входить — воно неперехідне («зрение ослабевает»).
const MINE_ACTIVE = /^(?:усилива|усугубля|обостря|ухудша|уменьша|облегча|улучша|смягча|успокаива|ослабля|устраня|снима|прекраща)(?:ет|ют)$/i;
// Прийменники й прислівники часу, з яких починається обставина
const PREP_STRONG = cy(/^(?:от|при|после|во|в|на|под|над|из-за|с|со|к|ко|по|около|перед|через|вследствие|благодаря|если|когда|лежа|сидя|стоя|утром|утрам|вечером|вечерам|ночью|ночам|днем|днём|летом|зимой|весной|осенью|натощак|стоит)\b/);
const PREP_WEAK = cy(/^(?:от|при|после|во|вследствие|утром|утрам|вечером|вечерам|ночью|ночам|днем|днём|летом|зимой|весной|осенью|натощак)\b/);
// Заперечення та порівняння: «не проходит от кашля», «лучше всего», «тем хуже»
const MINE_NEG = cy(/(?:\bне\b|\bни\b|\bбез\b)\s*(?:\S+\s+){0,2}$/);
const MINE_CMP = cy(/^(?:всего|всех|чем\b|бы\b)|^\s*(?:же|ли)\b/);
const MINE_CMP_LEFT = cy(/(?:\bтем|\bчем|\bнаоборот|\bне\b|\bни\b)\s*(?:\S+\s+){0,1}$/);
// Обриви підрядного речення: далі йде не обставина, а наслідок
const MINE_STOP = cy(/\b(?:поэтому|потому что|так как|хотя|однако|причем|вследствие чего|что бы|которы|котором|которая|которому)\b/);
const MINE_SUB = cy(/^(?:когда|если|чтобы|пока)\b/);   // «не переносит, когда …»
const MINE_STRIP = /\*\*|_/g;

const words = s => s.split(/\s+/).filter(Boolean);

// Обрізає вікно: до крапки з комою, до дужки, до сполучника-наслідку, до ліміту символів
// (по межі слова). Дужка й «поэтому/которая…» — це вже не обставина, а пояснення симптому.
function cutWindow(s, limit) {
  let t = s.split(/[;(]/)[0];
  const st = t.toLowerCase().replace(/ё/g, 'е').search(MINE_STOP);
  if (st > 0) t = t.slice(0, st);
  if (t.length > limit) {
    const cut = t.lastIndexOf(' ', limit);
    t = t.slice(0, cut > 20 ? cut : limit);
  }
  return t.trim();
}

// Речення → [{d, c}] (0..n модальностей). Вікно шукається двічі:
// (а) після маркера, якщо в перших 4 словах є прийменник/прислівник часу;
// (б) перед маркером, якщо маркер — перехідне дієслово або обставина винесена вперед.
export function mineSentence(sent) {
  const out = [];
  const low = sent.toLowerCase().replace(/ё/g, 'е');
  const hits = [];
  MINE_RE.lastIndex = 0;
  let m;
  while ((m = MINE_RE.exec(low)) !== null) {
    if (!m[0]) { MINE_RE.lastIndex++; continue; }
    hits.push({ i: m.index, end: m.index + m[0].length, w: m[0] });
  }
  for (let k = 0; k < hits.length; k++) {
    const h = hits[k];
    let d = null, kind = null;
    for (const [re, dd, kk] of MINE_DIR) if (re.test(h.w)) { d = dd; kind = kk; break; }
    if (!d) continue;
    const left = low.slice(k > 0 ? hits[k - 1].end : 0, h.i);
    const right = low.slice(h.end, k + 1 < hits.length ? hits[k + 1].i : low.length).split(';')[0];
    if (kind !== 'direct' && MINE_NEG.test(left)) continue;         // «не проходит от», «без улучшения»
    if (MINE_CMP.test(right.trim()) || MINE_CMP_LEFT.test(left)) continue;  // «лучше всего», «тем хуже»
    const active = MINE_ACTIVE.test(h.w);
    let win = null, rule = kind === 'direct' ? 'direct' : 'after';
    if (kind === 'direct') {
      // «не переносит X»: X іде одразу після маркера й майже завжди коротке — тому
      // обрізаємо ще й на першій комі, крім звороту «не переносит, когда …»
      const r = right.replace(/^[\s,]+/, '');
      win = cutWindow(MINE_SUB.test(r) ? r : r.split(',')[0], 70);
    } else if (!active) {
      // після перехідного дієслова («уменьшает боль в суставах») іде симптом, а не обставина —
      // для таких маркерів працює лише правило (б)
      const prep = kind === 'weak' ? PREP_WEAK : PREP_STRONG;
      const toks = words(right).slice(0, 4);
      let at = -1, off = 0;
      for (const tok of toks) {
        const p = right.indexOf(tok, off);
        if (prep.test(tok)) { at = p; break; }
        off = p + tok.length;
      }
      if (at >= 0) win = cutWindow(right.slice(at), 80);
    }
    if (!win) {
      // (б) обставина перед маркером. Якщо попередній маркер стоїть у тій самій клаузі
      // (між ними немає коми чи крапки з комою), текст перед нами — це його вікно, не наше:
      // «усиливается в полдень и исчезает к вечеру» не дає «лучше в полдень».
      const bStart = Math.max(left.lastIndexOf(';'), left.lastIndexOf(','), left.lastIndexOf(':'), left.lastIndexOf('—'), left.lastIndexOf('–'), left.lastIndexOf('('));
      const before = left.slice(bStart + 1).trim();
      const ws = words(before);
      if (ws.length && ws.length <= 8 && !MINE_STOP.test(before) && (k === 0 || bStart >= 0) && (active || PREP_STRONG.test(before))) { win = before; rule = 'before'; }
    }
    if (!win || win.length < 3) continue;
    const c = classifyMod(win);
    if (c.length) out.push({ d, c, w: win, rule });
  }
  return out;
}

// Абзаци симптомного розділу → [{d, c, t (речення), sec, para, sent}] + статистика.
// `split` — розбивач на речення (SC.splitSentences із search-core.js), щоб номери речень
// збігалися з тими, за якими вирівнюється український текст.
export function mineModalities(paras, split, sec) {
  const items = [];
  const stats = { sentences: 0, marked: 0, mined: 0 };
  paras.forEach((p, pi) => {
    const sents = split(p.replace(MINE_STRIP, ''));
    sents.forEach((sent, si) => {
      stats.sentences++;
      const got = mineSentence(sent);
      if (!got.length) return;
      stats.marked++;
      for (const g of got) { items.push({ d: g.d, c: g.c, t: sent.trim(), sec, para: pi, sent: si }); stats.mined++; }
    });
  });
  return { items, stats };
}
